import {readFile,writeFile} from 'node:fs/promises';
const core=['theme','foundation','typography','components','layout','patterns','forms','source-profile'];
const reference=['shell','documents','examples','examples-family','components','scientific'];
const files=[...core.map(name=>`dist/${name}.css`),...reference.map(name=>`styles/reference/${name}.css`),'styles/dashboards.css','styles/dashboard-controls.css'];
const css=await Promise.all(files.map(file=>readFile(file,'utf8')));
await writeFile('dist/reference.css','/* Generated by Core. Astro and Jekyll consume these identical bytes. */\n'+css.join('\n'));
await writeFile('dist/dashboards.css',await readFile('styles/dashboards.css','utf8')+'\n'+await readFile('styles/dashboard-controls.css','utf8'));
for(const name of ['fonts','shell'])await writeFile(`dist/reference-${name}.css`,await readFile(`styles/reference/${name}.css`));
